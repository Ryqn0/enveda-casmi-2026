"""Phase 0 EDA: profile train/test and estimate the library-search ceiling.

Writes docs/01-data-notes.md. Reads only scalar columns from train.parquet —
the ms2_* list columns are ~2.7GB of the file and are not needed here.

    uv run python scripts/eda.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
import pyarrow.parquet as pq

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
OUT = ROOT / "docs" / "01-data-notes.md"

PPM = 15e-6  # precursor mass tolerance used by the public baselines

SCALARS = [
    "ingest_lib",
    "normalized_smiles",
    "inchikey14",
    "molecular_formula",
    "ionization_mode",
    "instrument_type",
    "adduct",
    "precursor_mz",
    "num_peaks",
]

lines: list[str] = []


def say(s: str = "") -> None:
    print(s)
    lines.append(s)


def counts(series: pd.Series, name: str, top: int = 10) -> None:
    """Markdown table of the most common values, with share of total."""
    vc = series.value_counts()
    say(f"**{name}** — {vc.size:,} distinct")
    say()
    say("| value | count | share |")
    say("|---|---:|---:|")
    for val, n in vc.head(top).items():
        say(f"| `{val}` | {n:,} | {n / len(series):.1%} |")
    if vc.size > top:
        say(f"| _… {vc.size - top:,} more_ | {vc.iloc[top:].sum():,} | "
            f"{vc.iloc[top:].sum() / len(series):.1%} |")
    say()


def describe_peaks(arr: np.ndarray, name: str) -> None:
    q = np.percentile(arr, [0, 25, 50, 75, 95, 100])
    say(f"**{name}** — min {q[0]:.0f} · p25 {q[1]:.0f} · median {q[2]:.0f} · "
        f"p75 {q[3]:.0f} · p95 {q[4]:.0f} · max {q[5]:.0f}")
    say()


def main() -> None:
    say("# Data notes — CASMI 2026")
    say()
    say("_Generated by `scripts/eda.py`. Do not edit by hand._")
    say()
    say("> **WARNING** — the \"Test set\" section profiles the *placeholder*")
    say("> `test.parquet`, which is built from training rows and is replaced by")
    say("> the hidden test set at re-run. The real test set spans monoisotopic")
    say("> masses 157-1159 Da across 10 adducts, so nothing here describes what")
    say("> will actually be scored. See docs/02-false-alarm-placeholder-test-set.md.")
    say()

    # ---------------------------------------------------------------- test
    test = pd.read_parquet(RAW / "test.parquet")
    n_mol = test.molecule_id.nunique()

    say("## Test set")
    say()
    say(f"- **{len(test):,} spectra** over **{n_mol:,} molecules**")
    spm = test.groupby("molecule_id").size()
    say(f"- spectra per molecule: min {spm.min()} · median {spm.median():.0f} · "
        f"max {spm.max()}")
    say(f"- precursor m/z range: {test.precursor_mz.min():.1f} – "
        f"{test.precursor_mz.max():.1f}")
    say()
    counts(test.adduct, "Test adducts")
    counts(test.instrument_type, "Test instruments")
    counts(test.ionization_mode, "Test ionization modes")
    describe_peaks(test.ms2_mzs.str.len().to_numpy(), "Test peaks per spectrum")

    # stepped vs single collision energy
    n_step = (test.collision_energy_ev.str.len() > 1).sum()
    say(f"**Collision energy** — {n_step:,} stepped spectra "
        f"({n_step / len(test):.0%}), {len(test) - n_step:,} single-energy.")
    say()

    # --------------------------------------------------------------- train
    say("## Training set")
    say()
    pf = pq.ParquetFile(RAW / "train.parquet")
    say(f"- **{pf.metadata.num_rows:,} spectra** "
        f"({pf.metadata.num_rows / len(test):.0f}x the test set)")

    train = pq.read_table(RAW / "train.parquet", columns=SCALARS).to_pandas()
    say(f"- **{train.inchikey14.nunique():,} unique structures** (InChIKey14)")
    say(f"- **{train.molecular_formula.nunique():,} unique molecular formulas**")
    say(f"- precursor m/z range: {train.precursor_mz.min():.1f} – "
        f"{train.precursor_mz.max():.1f}")
    say()
    counts(train.ingest_lib, "Source libraries")
    counts(train.adduct, "Train adducts")
    counts(train.instrument_type, "Train instruments")
    counts(train.ionization_mode, "Train ionization modes")
    describe_peaks(train.num_peaks.to_numpy(), "Train peaks per spectrum")

    # ------------------------------------------------- train/test mismatch
    say("## Train vs test overlap")
    say()
    tt_inst = set(test.instrument_type.unique())
    tr_inst = set(train.instrument_type.unique())
    say(f"- test instruments: {sorted(tt_inst)}")
    share = train.instrument_type.isin(tt_inst).mean()
    say(f"- share of training spectra on a **test instrument**: **{share:.1%}**")
    say(f"- instruments in train but not test: {len(tr_inst - tt_inst):,}")
    say()
    tt_add = set(test.adduct.unique())
    say(f"- test adducts: {sorted(tt_add)}")
    say(f"- share of training spectra with a **test adduct**: "
        f"**{train.adduct.isin(tt_add).mean():.1%}**")
    say()

    # ------------------------------------ the number that sets the ceiling
    say("## Library-search ceiling")
    say()
    say(f"For each test molecule: does the training set contain **any** structure "
        f"whose precursor m/z matches within ±{PPM * 1e6:.0f} ppm, with the same "
        f"adduct? This is a *necessary* condition for spectral library search to "
        f"find the answer — not a sufficient one, since a mass match is not a "
        f"structure match.")
    say()

    probe = test.groupby("molecule_id").agg(
        precursor_mz=("precursor_mz", "first"), adduct=("adduct", "first")
    )

    rows = []
    for adduct, grp in probe.groupby("adduct"):
        pool = train.loc[train.adduct == adduct, ["precursor_mz", "inchikey14"]]
        pool = pool.sort_values("precursor_mz")
        mz = pool.precursor_mz.to_numpy()
        keys = pool.inchikey14.to_numpy()
        for mid, row in grp.iterrows():
            lo, hi = row.precursor_mz * (1 - PPM), row.precursor_mz * (1 + PPM)
            i, j = np.searchsorted(mz, [lo, hi])
            rows.append(
                {
                    "molecule_id": mid,
                    "adduct": adduct,
                    "n_spectra": j - i,
                    "n_structures": len(np.unique(keys[i:j])) if j > i else 0,
                }
            )

    hits = pd.DataFrame(rows).set_index("molecule_id")
    hits.to_csv(ROOT / "data" / "precursor_hits.csv")

    have = (hits.n_structures > 0).mean()
    say(f"- **{have:.1%}** of test molecules have at least one mass-matched "
        f"training structure ({(hits.n_structures > 0).sum()}/{len(hits)}).")
    say(f"- **{(hits.n_structures == 0).sum()}** have none — those are "
        f"unreachable by library search and need de novo or a wider candidate pool.")
    say()
    ns = hits.n_structures
    say("**Candidate structures per test molecule** (mass + adduct filter alone)")
    say()
    say("| percentile | structures |")
    say("|---|---:|")
    for p in (25, 50, 75, 90, 100):
        say(f"| p{p} | {np.percentile(ns, p):,.0f} |")
    say()
    say(f"Median **{ns.median():.0f}** candidates for 25 slots — so mass filtering "
        f"alone is nowhere near enough; the ranking model does the real work.")
    say()

    OUT.write_text("\n".join(lines) + "\n")
    print(f"\n-> wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
